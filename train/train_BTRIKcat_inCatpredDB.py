class TokenDataset(Dataset):
    def __init__(self, split_dir: str | Path, label_processor: Optional[LabelProcessor] = None, fit_label_processor: bool = False):
        self.split_dir = Path(split_dir)
        flat_protein_path = self.split_dir / "protein_tokens_flat.dat"
        offsets_path = self.split_dir / "protein_offsets.npy"
        if flat_protein_path.exists() and offsets_path.exists():
            stats_path = self.split_dir / "stats.json"
            stats = json.loads(stats_path.read_text(encoding="utf-8")) if stats_path.exists() else {}
            self.protein_storage = "flat_memmap"
            self.protein_dim = int(stats.get("protein_feature_dim", 2560))
            dtype = np.dtype(stats.get("save_dtype", "float16"))
            self.protein_offsets = np.load(offsets_path, mmap_mode="r")
            self.protein = np.memmap(flat_protein_path, mode="r", dtype=dtype)
            expected_values = int(self.protein_offsets[-1]) * self.protein_dim
            if self.protein.size != expected_values:
                raise ValueError(
                    f"Flat protein feature size mismatch in {self.split_dir}: "
                    f"expected {expected_values}, got {self.protein.size}"
                )
        else:
            self.protein_storage = "array"
            self.protein_dim = None
            self.protein_offsets = None
            self.protein = safe_np_load(self.split_dir / "protein_tokens.npy")
        self.rxnfp = safe_np_load(self.split_dir / "rxnfp_tokens.npy")

        chemberta_path = self.split_dir / "chemberta_tokens.npy"
        fallback_path = self.split_dir / "molbert_tokens.npy"
        if chemberta_path.exists():
            self.chemberta = safe_np_load(chemberta_path)
            self.chemberta_source = "chemberta_tokens.npy"
        elif fallback_path.exists():
            self.chemberta = safe_np_load(fallback_path)
            self.chemberta_source = "molbert_tokens.npy"
        else:
            raise FileNotFoundError(f"Missing chemberta_tokens.npy or molbert_tokens.npy in {self.split_dir}")

        self.labels = safe_np_load(self.split_dir / "labels.npy")
        self.meta = pd.read_parquet(self.split_dir / "meta.parquet")

        protein_samples = (
            len(self.protein_offsets) - 1
            if self.protein_storage == "flat_memmap"
            else len(self.protein)
        )
        lengths = [protein_samples, len(self.rxnfp), len(self.chemberta), len(self.labels), len(self.meta)]
        if len(set(lengths)) != 1:
            raise ValueError(f"Length mismatch in {self.split_dir}: {lengths}")

        self.label_processor = label_processor or LabelProcessor()
        if fit_label_processor:
            self.label_processor.fit(self.labels)
        self.labels_proc = self.label_processor.transform(self.labels)

    def __len__(self) -> int:
        return len(self.labels)

    @property
    def protein_lengths(self) -> np.ndarray:
        if self.protein_storage == "flat_memmap":
            return np.diff(self.protein_offsets).astype(np.int64, copy=False)
        if getattr(self.protein, "dtype", None) == object:
            return np.asarray([np.asarray(item).shape[0] for item in self.protein], dtype=np.int64)
        return np.full(len(self.protein), int(self.protein.shape[1]), dtype=np.int64)

    def __getitem__(self, idx: int):
        if self.protein_storage == "flat_memmap":
            start = int(self.protein_offsets[idx])
            end = int(self.protein_offsets[idx + 1])
            protein = np.asarray(self.protein[start * self.protein_dim:end * self.protein_dim]).reshape(
                end - start, self.protein_dim
            )
        else:
            protein = np.asarray(self.protein[idx])
        # Keep feature tensors in half precision from storage through the
        # DataLoader. CUDA AMP consumes these directly; non-AMP paths cast back
        # to float32 in run_epoch/predict_processed for compatibility.
        protein = torch.from_numpy(protein.copy()).to(dtype=torch.float16)
        rxnfp = torch.from_numpy(np.asarray(self.rxnfp[idx]).copy()).to(dtype=torch.float16)
        chemberta = torch.from_numpy(np.asarray(self.chemberta[idx]).copy()).to(dtype=torch.float16)
        label = torch.tensor(float(self.labels_proc[idx]), dtype=torch.float32)
        return protein, rxnfp, chemberta, label

    @property
    def feature_shapes(self) -> Dict[str, List[int]]:
        if self.protein_storage == "flat_memmap":
            protein_shape = [len(self.labels), "variable_L", self.protein_dim]
        else:
            protein_shape = list(self.protein.shape)
        if self.protein_storage != "flat_memmap" and getattr(self.protein, "dtype", None) == object and len(self.protein):
            protein_shape = [len(self.protein), "variable_L", int(np.asarray(self.protein[0]).shape[-1])]
        return {
            "protein": protein_shape,
            "rxnfp": list(self.rxnfp.shape),
            "chemberta": list(self.chemberta.shape),
            "labels": list(self.labels.shape),
            "chemberta_source": self.chemberta_source,
        }


def collate_token_batch(batch):
    """Pad protein residues to the longest sequence in this batch only."""
    proteins, rxnfp, chemberta, labels = zip(*batch)
    feature_dim = int(proteins[0].shape[-1])
    max_length = max(int(protein.shape[0]) for protein in proteins)
    padded = torch.zeros(
        len(proteins), max_length, feature_dim, dtype=proteins[0].dtype
    )
    protein_mask = torch.zeros(len(proteins), max_length, dtype=torch.bool)
    for idx, protein in enumerate(proteins):
        length = int(protein.shape[0])
        padded[idx, :length] = protein
        protein_mask[idx, :length] = True
    return (
        padded,
        torch.stack(rxnfp),
        torch.stack(chemberta),
        torch.stack(labels),
        protein_mask,
    )


# ===================== Overlap checks =====================
def exact_overlap_report(train_meta: pd.DataFrame, eval_meta: pd.DataFrame) -> Dict[str, Dict[str, Any]]:
    checks = {
        "sequence": ["sequence"],
        "reaction": ["reaction_smiles"],
        "sequence_reaction_pair": ["sequence", "reaction_smiles"],
    }
    report: Dict[str, Dict[str, Any]] = {}
    for name, cols in checks.items():
        missing = [c for c in cols if c not in train_meta.columns or c not in eval_meta.columns]
        if missing:
            report[name] = {"columns": cols, "skipped": True, "missing_columns": missing}
            continue
        train_set = set(map(tuple, train_meta[cols].astype(str).itertuples(index=False, name=None)))
        eval_set = set(map(tuple, eval_meta[cols].astype(str).itertuples(index=False, name=None)))
        overlap = train_set & eval_set
        report[name] = {
            "columns": cols,
            "train_unique": len(train_set),
            "eval_unique": len(eval_set),
            "overlap_count": len(overlap),
            "overlap_ratio_eval_unique": float(len(overlap) / max(1, len(eval_set))),
        }
    return report

