class RankLoss(nn.Module):
    """Mean hinge loss over unordered pairs with unequal targets.

    Parameters
    ----------
    margin : float
        Ranking margin m in the same units as the inputs. When training labels
        are standardized by the training-set mean and standard deviation, the
        margin is expressed in units of the training-label standard deviation.
    """

    def __init__(self, margin: float = 1.0):
        super().__init__()
        self.margin = margin

    def forward(self, pred: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
        pred = pred.reshape(-1)
        target = target.reshape(-1)
        if pred.numel() != target.numel():
            raise ValueError("pred and target must contain the same number of values")
        n = pred.numel()
        if n < 2:
            # Differentiable zero so that degenerate batches keep the graph intact.
            return pred.sum() * 0.0

        pred_diff = pred.unsqueeze(1) - pred.unsqueeze(0)
        target_diff = target.unsqueeze(1) - target.unsqueeze(0)

        # Upper triangle: each unordered pair is evaluated once.
        upper = torch.triu(torch.ones_like(target_diff, dtype=torch.bool), diagonal=1)
        # Comparable pairs: distinct targets only. Ties are dropped here, and the
        # same mask defines the denominator below.
        valid = upper & target_diff.ne(0)

        # sign() makes this correct for both orientations; no pair is skipped
        # because the "wrong" orientation happens to fall in the lower triangle.
        signed_pred_diff = pred_diff * target_diff.sign()
        pair_loss = F.relu(self.margin - signed_pred_diff)

        # Mean over the comparable pairs actually contributing to the numerator.
        return (pair_loss * valid.to(pair_loss.dtype)).sum() / valid.sum().clamp_min(1)

