    logger.info("  dropout: %.2f", cfg.dropout)
    logger.info("  ffn_expansion: %d", cfg.ffn_expansion)
    logger.info("  pooling: %s", cfg.pooling)
    logger.info("  fusion: %s", cfg.fusion)
    logger.info("  use_type_embeddings: %s", cfg.use_type_embeddings)
    logger.info("=" * 80)
    logger.info("Data Parameters:")
    logger.info("  num_workers: %d", cfg.num_workers)
    logger.info("  pin_memory: %s", cfg.pin_memory)
    logger.info("  use_amp: %s", cfg.use_amp)
