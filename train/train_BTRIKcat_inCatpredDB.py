    logger.info("=" * 80)

    models: List[nn.Module] = []
    label_processors: List[LabelProcessor] = []
    for result in seed_results:
        ckpt_path = Path(result["seed_dir"]) / "best_model.pth"
        if not ckpt_path.exists():
            raise FileNotFoundError(f"Missing best checkpoint for seed {result['seed']}: {ckpt_path}")
        ckpt = load_checkpoint(ckpt_path, map_location=cfg.device)

        label_processor = LabelProcessor()
        label_processor.load_state_dict(ckpt["label_processor"])
        label_processors.append(label_processor)

